from pathlib import Path
from fpdf import FPDF

class BriefPDFExporter(FPDF):

    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.set_text_color(0, 102, 104)  # University accent color
        self.cell(
            0, 10, "UNIVERSITY ASSESSMENT BRIEF",  border=0, new_x="LMARGIN", new_y="NEXT", align="C"
        )
        self.ln(2)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(
            0,
            10,
            f"Page {self.page_no()}/{{nb}} - Generated by Academic RAG System",
            align="C",
        )

def markdown_to_pdf(md_content: str, output_path: Path) -> Path:
    """Converts a Markdown assessment brief into a styled PDF document."""
    pdf = BriefPDFExporter()
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.set_font("Helvetica", size=10)

    lines = md_content.split("\n")
    for line in lines:
        line_str = line.strip()

        if line_str.startswith("# "):
            pdf.ln(4)
            pdf.set_font("Helvetica", "B", 14)
            pdf.set_text_color(0, 51, 102)
            pdf.multi_cell(0, 8, line_str.replace("# ", ""))
            pdf.ln(2)

        elif line_str.startswith("## "):
            pdf.ln(3)
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_text_color(0, 51, 102)
            pdf.multi_cell(0, 7, line_str.replace("## ", ""))
            pdf.ln(1)

        elif line_str.startswith("### "):
            pdf.ln(2)
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(51, 51, 51)
            pdf.multi_cell(0, 6, line_str.replace("### ", ""))

        elif line_str.startswith("* ") or line_str.startswith("- "):
            pdf.set_font("Helvetica", size=10)
            pdf.set_text_color(34, 34, 34)
            bullet_text = line_str[2:].replace("**", "")
            pdf.multi_cell(0, 5, f"  • {bullet_text}")

        elif line_str.startswith("|"):
            # Render Markdown table row as formatted text
            pdf.set_font("Courier", size=9)
            pdf.set_text_color(0, 0, 0)
            pdf.multi_cell(0, 5, line_str)

        elif line_str:
            pdf.set_font("Helvetica", size=10)
            pdf.set_text_color(34, 34, 34)
            clean_line = line_str.replace("**", "")
            pdf.multi_cell(0, 5, clean_line)
            pdf.ln(1)

    pdf.output(str(output_path))
    return output_path
